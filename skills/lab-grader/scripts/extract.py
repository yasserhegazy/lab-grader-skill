#!/usr/bin/env python3
"""Extract text, screenshots, OCR and metadata from every student submission.

Zero Claude tokens: everything here is local (PyMuPDF, zipfile, Pillow, tesseract).

Usage:
    python3 extract.py <submissions_dir> <work_dir> [--max-images 40] [--jobs 8]

Produces, for each student, <work_dir>/extracted/<participant_id>/:
    text.txt     document text, split by "===== page N ====="
    ocr.txt      OCR of each screenshot, split by "===== img_XX.png ====="
    images/      screenshots (filtered: no icons/logos fragments), PNG, max 1600px wide
    meta.json    file metadata + automatic flags
and <work_dir>/manifest.json with one row per student.
"""
import argparse
import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from concurrent.futures import ProcessPoolExecutor
from xml.etree import ElementTree as ET

import fitz  # PyMuPDF
from PIL import Image, ImageOps, ImageStat

FOLDER_RE = re.compile(r"^(?P<name>.+?)_(?P<pid>\d+)_assign(?:submission|ment)_(?:file|onlinetext)_?$")
CODE_EXT = {".py", ".c", ".cpp", ".h", ".java", ".js", ".ts", ".sh", ".txt", ".md", ".html", ".css", ".sql", ".ipynb"}
IMG_EXT = {".png", ".jpg", ".jpeg", ".bmp", ".gif", ".webp"}
# Terminal output is often cropped to a wide, short strip (e.g. 600x40), so filter on area,
# not height. Below this are icons and fragments of vector drawings.
MIN_W, MIN_H, MIN_AREA = 150, 24, 8000
HAS_TESSERACT = shutil.which("tesseract") is not None

# Producers/authors that mean "the document was generated by a script", which
# students almost never do by hand but AI chat tools do routinely.
SCRIPT_GENERATORS = ["python-docx", "reportlab", "fpdf", "docx.js", "pandoc", "weasyprint", "wkhtmltopdf", "openpyxl", "wordcraft"]
BROWSER_PRINT = ["skia/pdf", "chromium", "mozilla/", "chrome"]


def dhash(img, size=8):
    """64-bit difference hash, robust to rescaling/recompression."""
    g = img.convert("L").resize((size + 1, size), Image.LANCZOS)
    px = list(g.getdata())
    bits = 0
    for r in range(size):
        for c in range(size):
            bits = (bits << 1) | (px[r * (size + 1) + c] > px[r * (size + 1) + c + 1])
    return f"{bits:016x}"


def save_image(raw_bytes, out_path):
    """Normalise to PNG, downscale large images. Returns (w, h, dhash) or None if too small."""
    try:
        img = Image.open(io.BytesIO(raw_bytes))
        img.load()
    except Exception:
        return None
    if img.width < MIN_W or img.height < MIN_H or img.width * img.height < MIN_AREA:
        return None
    if img.mode not in ("RGB", "L"):
        img = img.convert("RGB")
    if ImageStat.Stat(img.convert("L")).stddev[0] < 3:   # blank / alpha mask
        return None
    if img.width > 1600:
        img = img.resize((1600, int(img.height * 1600 / img.width)), Image.LANCZOS)
    img.save(out_path, "PNG", optimize=True)
    return img.width, img.height, dhash(img)


def ocr_image(path):
    """Terminal screenshots are usually light-on-dark; tesseract wants dark-on-light."""
    if not HAS_TESSERACT:
        return ""
    try:
        img = Image.open(path).convert("L")
        if sum(img.getdata()) / (img.width * img.height) < 110:
            img = ImageOps.invert(img)
        if img.width < 1200:
            img = img.resize((img.width * 2, img.height * 2), Image.LANCZOS)
        tmp = path + ".ocr.png"
        img.save(tmp)
        # One thread per tesseract: we already run one process per CPU, and
        # tesseract's own OpenMP threads oversubscribe the machine ~4x otherwise.
        env = {**os.environ, "OMP_THREAD_LIMIT": "1"}
        out = subprocess.run(["tesseract", tmp, "stdout", "--psm", "6"], capture_output=True, text=True, timeout=120, env=env).stdout
        os.remove(tmp)
        return out.strip()
    except Exception as e:
        return f"[OCR failed: {e}]"


def pdf_extract(path, img_dir, img_counter, max_images, seen):
    doc = fitz.open(path)
    pages, images = [], []
    for pno, page in enumerate(doc, 1):
        pages.append(f"===== page {pno} =====\n{page.get_text()}")
        page_imgs = page.get_images(full=True)
        seen.update(info[1] for info in page_imgs if info[1])  # soft masks are not pictures
        for info in page_imgs:
            xref = info[0]
            if xref in seen or len(images) >= max_images:
                continue
            seen.add(xref)
            try:
                raw = doc.extract_image(xref)["image"]
            except Exception:
                continue
            name = f"img_{img_counter[0]:02d}.png"
            res = save_image(raw, os.path.join(img_dir, name))
            if res:
                images.append({"file": name, "page": pno, "w": res[0], "h": res[1], "dhash": res[2]})
                img_counter[0] += 1
    m = doc.metadata or {}
    meta = {
        "pages": doc.page_count,
        "creator": m.get("creator", ""), "producer": m.get("producer", ""), "author": m.get("author", ""),
        "title": m.get("title", ""), "created": m.get("creationDate", ""), "modified": m.get("modDate", ""),
    }
    return "\n".join(pages), images, meta


def docx_extract(path, img_dir, img_counter, max_images):
    ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
    z = zipfile.ZipFile(path)
    root = ET.fromstring(z.read("word/document.xml"))
    paras = ["".join(t.text or "" for t in p.iter(f"{{{ns['w']}}}t")) for p in root.iter(f"{{{ns['w']}}}p")]
    images = []
    for n in sorted(z.namelist()):
        if n.startswith("word/media/") and len(images) < max_images:
            name = f"img_{img_counter[0]:02d}.png"
            res = save_image(z.read(n), os.path.join(img_dir, name))
            if res:
                images.append({"file": name, "page": None, "w": res[0], "h": res[1], "dhash": res[2]})
                img_counter[0] += 1
    meta = {"pages": None}
    for part in ("docProps/core.xml", "docProps/app.xml"):
        if part in z.namelist():
            for el in ET.fromstring(z.read(part)).iter():
                tag = el.tag.split("}")[-1]
                if tag in ("creator", "lastModifiedBy", "created", "modified", "Application", "TotalTime", "Pages") and el.text:
                    meta[tag] = el.text
    meta["author"] = meta.get("creator", "")
    meta["producer"] = meta.get("Application", "")
    return "\n".join(paras), images, meta


def flags_from_meta(meta, fname):
    flags = []
    blob = " ".join(str(meta.get(k, "")) for k in ("creator", "producer", "author", "lastModifiedBy", "Application")).lower()
    for g in SCRIPT_GENERATORS:
        if g in blob:
            flags.append(f"META_SCRIPT_GENERATED:{g} (document produced by a program, typical of AI-chat-generated reports)")
    if any(b in blob for b in BROWSER_PRINT):
        flags.append("META_BROWSER_PRINT (printed from a browser: Google Docs, web page or AI chat; weak signal alone)")
    tt = meta.get("TotalTime")
    if tt is not None and str(tt).isdigit() and int(tt) <= 3:
        flags.append(f"META_DOCX_EDIT_TIME:{tt}min (document edited for almost no time)")
    return flags


def process(args):
    folder, sub_dir, work_dir, max_images = args
    m = FOLDER_RE.match(folder)
    name, pid = (m.group("name"), m.group("pid")) if m else (folder, hashlib.md5(folder.encode()).hexdigest()[:8])
    out = os.path.join(work_dir, "extracted", pid)
    img_dir = os.path.join(out, "images")
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(img_dir)

    texts, images, metas, flags, files = [], [], [], [], []
    counter = [1]
    src = os.path.join(sub_dir, folder)
    all_files = []
    for dp, _, fns in os.walk(src):
        for fn in sorted(fns):
            all_files.append(os.path.join(dp, fn))

    # unpack archives into the work dir (never execute anything from them)
    for f in list(all_files):
        if f.lower().endswith(".zip"):
            dest = os.path.join(out, "unzipped", os.path.basename(f))
            try:
                with zipfile.ZipFile(f) as z:
                    for member in z.namelist():
                        target = os.path.realpath(os.path.join(dest, member))
                        if target.startswith(os.path.realpath(dest)) and not member.endswith("/"):
                            os.makedirs(os.path.dirname(target), exist_ok=True)
                            with open(target, "wb") as fh:
                                fh.write(z.read(member))
                            all_files.append(target)
            except Exception as e:
                flags.append(f"ARCHIVE_ERROR:{os.path.basename(f)}:{e}")
        elif f.lower().endswith((".rar", ".7z")):
            flags.append(f"ARCHIVE_NEEDS_MANUAL_EXTRACT:{os.path.basename(f)}")

    seen = set()
    for f in all_files:
        ext = os.path.splitext(f)[1].lower()
        rel = os.path.relpath(f, src) if f.startswith(src) else os.path.relpath(f, out)
        files.append(rel)
        try:
            if ext == ".pdf":
                t, im, meta = pdf_extract(f, img_dir, counter, max_images, seen)
            elif ext == ".docx":
                t, im, meta = docx_extract(f, img_dir, counter, max_images)
            elif ext in IMG_EXT:
                name_ = f"img_{counter[0]:02d}.png"
                res = save_image(open(f, "rb").read(), os.path.join(img_dir, name_))
                t, im, meta = "", [], {"pages": None}
                if res:
                    im = [{"file": name_, "page": None, "w": res[0], "h": res[1], "dhash": res[2], "source": rel}]
                    counter[0] += 1
            elif ext in CODE_EXT:
                t, im, meta = open(f, encoding="utf-8", errors="replace").read(), [], {"pages": None}
            else:
                flags.append(f"UNSUPPORTED_FILE:{rel}")
                continue
        except Exception as e:
            flags.append(f"READ_ERROR:{rel}:{e}")
            continue
        meta["file"] = rel
        metas.append(meta)
        flags.extend(flags_from_meta(meta, rel))
        texts.append(f"##### FILE: {rel}\n{t}")
        images.extend(im)

    ocr_parts = []
    for im in images:
        txt = ocr_image(os.path.join(img_dir, im["file"]))
        im["ocr_chars"] = len(txt)
        ocr_parts.append(f"===== {im['file']} (page {im['page']}) =====\n{txt}")

    text = "\n".join(texts)
    with open(os.path.join(out, "text.txt"), "w") as fh:
        fh.write(text)
    with open(os.path.join(out, "ocr.txt"), "w") as fh:
        fh.write("\n".join(ocr_parts) if HAS_TESSERACT else "[tesseract not installed: open the images directly]")

    if not any(f.lower().endswith(".pdf") for f in files):
        flags.append("NOT_PDF (submission contains no PDF)")
    if len(re.sub(r"\s", "", text)) < 300:
        flags.append("LITTLE_TEXT (text mostly inside images or submission nearly empty)")
    if not images:
        flags.append("NO_SCREENSHOTS")

    row = {"participant_id": pid, "name": name, "folder": folder, "files": files,
           "pages": sum((m_.get("pages") or 0) for m_ in metas), "text_chars": len(text),
           "n_images": len(images), "ocr": HAS_TESSERACT, "flags": flags}
    with open(os.path.join(out, "meta.json"), "w") as fh:
        json.dump({**row, "file_meta": metas, "images": images}, fh, ensure_ascii=False, indent=1)
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("submissions_dir")
    ap.add_argument("work_dir")
    ap.add_argument("--max-images", type=int, default=40)
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    ap.add_argument("--only", nargs="*", help="participant ids to (re)process")
    a = ap.parse_args()

    folders = sorted(d for d in os.listdir(a.submissions_dir) if os.path.isdir(os.path.join(a.submissions_dir, d)))
    if a.only:
        folders = [f for f in folders if any(f"_{p}_" in f for p in a.only)]
    if not HAS_TESSERACT:
        print("WARNING: tesseract not found, no OCR. Install: sudo apt install tesseract-ocr", file=sys.stderr)
    with ProcessPoolExecutor(a.jobs) as ex:
        rows = list(ex.map(process, [(f, a.submissions_dir, a.work_dir, a.max_images) for f in folders]))

    man_path = os.path.join(a.work_dir, "manifest.json")
    if a.only and os.path.exists(man_path):
        old = {r["participant_id"]: r for r in json.load(open(man_path))}
        old.update({r["participant_id"]: r for r in rows})
        rows = sorted(old.values(), key=lambda r: r["participant_id"])
    with open(man_path, "w") as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=1)
    for r in rows:
        print(f"{r['participant_id']}  {r['pages'] or '-':>3}p {r['text_chars']:6}ch {r['n_images']:3}img  {r['name'][:30]}  {'; '.join(r['flags'])}")
    print(f"\n{len(rows)} submissions -> {man_path}")


if __name__ == "__main__":
    main()
